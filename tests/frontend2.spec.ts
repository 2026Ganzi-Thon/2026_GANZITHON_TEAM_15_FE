import { test, expect } from '@playwright/test'

test('목장 선택 → 어조 재확인 → 조언 보내기', async ({ page }) => {
  await page.goto('/farm')
  await expect(page.getByRole('heading', { name: '고민 목장' })).toBeVisible()
  await expect(page.locator('.pasture-sheep').first()).toBeVisible()
  await page.getByRole('link', { name: '조언하기', exact: true }).click()
  await page.getByRole('textbox', { name: '조언 내용' }).fill('더 노력해 보세요')
  await page.getByRole('button', { name: '털 한 올 보내기', exact: true }).click()
  await expect(page.getByText('다그치는 말처럼 들릴 수 있어요')).toBeVisible()
  await page.getByRole('button', { name: '이 문장으로 바꾸기' }).click()
  await page.getByRole('button', { name: '털 한 올 보내기', exact: true }).click()
  await expect(page.getByRole('heading', { name: '한 올 보냈어요' })).toBeVisible()
})

test('고민 올리기 → 내 고민 → 졸업 → 보관함', async ({ page }) => {
  await page.goto('/worries/new')
  await page.getByRole('textbox', { name: '고민 내용' }).fill('내일 발표가 걱정돼요')
  await page.getByRole('button', { name: '올리기', exact: true }).click()
  await expect(page.getByText('고민 양이 태어났어요')).toBeVisible()
  await page.getByRole('link', { name: '내 고민 보기' }).click()
  await page.getByRole('button', { name: '보관함으로 보내기' }).click()
  await page.getByRole('button', { name: '졸업시키기' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: '내 고민 목록으로' }).click()
  await page.getByRole('button', { name: '보관함' }).click()
  await expect(page.getByRole('link', { name: '내일 발표가 걱정돼요' })).toBeVisible()
})

test('닉네임 중복 오류와 저장, 차단과 해제', async ({ page }) => {
  await page.goto('/me/nickname')
  const input = page.getByRole('textbox')
  await expect(input).toHaveValue('다정한 목동')
  await input.fill('조용한 목동')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('이미 사용 중')
  await input.fill('푸른 목동')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText('푸른 목동')).toBeVisible()
  await page.goto('/worries/1')
  await page.getByRole('button', { name: '더보기' }).click()
  await page.getByRole('button', { name: '이 목동 차단하기' }).click()
  await page.getByRole('button', { name: '차단하기', exact: true }).click()
  await expect(page).toHaveURL('/farm')
  await page.getByRole('link', { name: '나', exact: true }).click()
  await page.getByRole('link', { name: '차단한 목동 관리' }).click()
  await page.getByRole('button', { name: '해제', exact: true }).click()
  await page.getByRole('button', { name: '해제하기' }).click()
  await expect(page.getByText('차단한 목동이 없어요')).toBeVisible()
})

test('신고와 하트, 모바일 레이아웃 및 에셋', async ({ page }) => {
  await page.goto('/worries/9')
  await page.getByRole('button', { name: '고마워요 보내기' }).click()
  await expect(page.getByRole('button', { name: '고마워요 보냄' })).toBeDisabled()
  await page.getByRole('button', { name: '더보기' }).click()
  await page.getByRole('button', { name: '신고하기', exact: true }).click()
  await page.getByRole('radio', { name: '악성 표현이에요' }).check()
  await page.getByRole('button', { name: '신고하기', exact: true }).click()
  await expect(page.getByText('신고했어요')).toBeVisible()
  await page.getByRole('button', { name: '확인', exact: true }).click()
  await expect(page.locator('.pasture')).toBeVisible()
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/farm-mobile.png', fullPage: true })
})
